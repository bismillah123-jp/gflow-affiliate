VNC_FILE_KEY = bytes([23, 82, 107, 6, 35, 78, 88, 7])


def _deskey(key8: bytes, decrypt: bool = False) -> list[int]:
    pc1m = [0] * 56
    for j in range(56):
        l = PC1[j]
        pc1m[j] = (key8[l >> 3] >> (l & 7)) & 1
    knl = [0] * 32
    for i in range(16):
        r = TOTROT[i]
        pcr = ([pc1m[(j + r) % 28] for j in range(28)] +
               [pc1m[28 + ((j + r) % 28)] for j in range(28)])
        m = ((15 - i) << 1) if decrypt else (i << 1)
        n = m + 1
        a = b = 0
        for j in range(24):
            if pcr[PC2[j]]:
                a |= BIGBYTE[j]
            if pcr[PC2[j + 24]]:
                b |= BIGBYTE[j]
        knl[m], knl[n] = a, b
    # cookey
    dough = [0] * 32
    for i in range(16):
        raw0, raw1 = knl[2 * i], knl[2 * i + 1]
        dough[2 * i] = (((raw0 & 0x00FC0000) << 6) | ((raw0 & 0x00000FC0) << 10) |
                        ((raw1 & 0x00FC0000) >> 10) | ((raw1 & 0x00000FC0) >> 6)) & M32
        dough[2 * i + 1] = (((raw0 & 0x0003F000) << 12) | ((raw0 & 0x0000003F) << 16) |
                            ((raw1 & 0x0003F000) >> 4) | (raw1 & 0x0000003F)) & M32
    return dough


def _desfunc(block: list[int], keys: list[int]) -> list[int]:
    leftt, right = block[0], block[1]
    work = ((leftt >> 4) ^ right) & 0x0F0F0F0F
    right ^= work
    leftt ^= (work << 4) & M32
    work = ((leftt >> 16) ^ right) & 0x0000FFFF
    right ^= work
    leftt ^= (work << 16) & M32
    work = ((right >> 2) ^ leftt) & 0x33333333
    leftt ^= work
    right ^= (work << 2) & M32
    work = ((right >> 8) ^ leftt) & 0x00FF00FF
    leftt ^= work
    right ^= (work << 8) & M32
    right = ((right << 1) | ((right >> 31) & 1)) & M32
    work = (leftt ^ right) & 0xAAAAAAAA
    leftt ^= work
    right ^= work
    leftt = ((leftt << 1) | ((leftt >> 31) & 1)) & M32

    k = 0
    for _ in range(8):
        work = (((right << 28) | (right >> 4)) & M32) ^ keys[k]
        k += 1
        fval = (SP7[work & 0x3F] | SP5[(work >> 8) & 0x3F] |
                SP3[(work >> 16) & 0x3F] | SP1[(work >> 24) & 0x3F])
        work = (right ^ keys[k]) & M32
        k += 1
        fval |= (SP8[work & 0x3F] | SP6[(work >> 8) & 0x3F] |
                 SP4[(work >> 16) & 0x3F] | SP2[(work >> 24) & 0x3F])
        leftt ^= fval
        work = (((leftt << 28) | (leftt >> 4)) & M32) ^ keys[k]
        k += 1
        fval = (SP7[work & 0x3F] | SP5[(work >> 8) & 0x3F] |
                SP3[(work >> 16) & 0x3F] | SP1[(work >> 24) & 0x3F])
        work = (leftt ^ keys[k]) & M32
        k += 1
        fval |= (SP8[work & 0x3F] | SP6[(work >> 8) & 0x3F] |
                 SP4[(work >> 16) & 0x3F] | SP2[(work >> 24) & 0x3F])
        right ^= fval

    right = ((right << 31) | (right >> 1)) & M32
    work = (leftt ^ right) & 0xAAAAAAAA
    leftt ^= work
    right ^= work
    leftt = ((leftt << 31) | (leftt >> 1)) & M32
    work = ((leftt >> 8) ^ right) & 0x00FF00FF
    right ^= work
    leftt ^= (work << 8) & M32
    work = ((leftt >> 2) ^ right) & 0x33333333
    right ^= work
    leftt ^= (work << 2) & M32
    work = ((right >> 16) ^ leftt) & 0x0000FFFF
    leftt ^= work
    right ^= (work << 16) & M32
    work = ((right >> 4) ^ leftt) & 0x0F0F0F0F
    leftt ^= work
    right ^= (work << 4) & M32
    # d3des menyimpan hasil akhir dengan urutan half terbalik
    # dibanding konvensi FIPS (sesuai oracle C)
    return [right & M32, leftt & M32]


def d3des(key8: bytes, data8: bytes, decrypt: bool = False) -> bytes:
    """Satu blok d3des ala TigerVNC (setara deskey+des di d3des.c)."""
    keys = _deskey(key8, decrypt)
    w0 = int.from_bytes(data8[0:4], "big")
    w1 = int.from_bytes(data8[4:8], "big")
    o0, o1 = _desfunc([w0, w1], keys)
    return o0.to_bytes(4, "big") + o1.to_bytes(4, "big")


def obfuscate(password: str | bytes) -> bytes:
    """Password -> 8 byte isi file ~/.vnc/passwd."""
    if isinstance(password, str):
        password = password.encode("utf-8", "ignore")
    plain = password[:8].ljust(8, b"\x00")
    return d3des(VNC_FILE_KEY, plain)


def deobfuscate(blob: bytes) -> bytes:
    return d3des(VNC_FILE_KEY, blob[:8], decrypt=True).rstrip(b"\x00")


def main() -> None:
    data = sys.stdin.buffer.read().strip()
    if not data:
        sys.exit("password kosong (kirim via stdin)")
    out = Path(os.environ.get("VNCPASSWD_FILE",
                              str(Path.home() / ".vnc" / "passwd")))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(obfuscate(data))
    os.chmod(out, 0o600)
    print(f"✔ {out}")


if __name__ == "__main__":
    main()
